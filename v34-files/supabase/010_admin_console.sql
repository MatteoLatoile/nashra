-- Apply AFTER 004..009. Repeatable. Does NOT enable payments or Telegram sending.
DO $$ BEGIN
  IF to_regclass('public.delivery_queue') IS NULL THEN
    RAISE EXCEPTION 'NASHRA_SQL_010: missing delivery_queue (SQL 004).';
  END IF;
  IF to_regclass('public.nashra_entitlements') IS NULL THEN
    RAISE EXCEPTION 'NASHRA_SQL_010: missing nashra_entitlements (SQL 009).';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.nashra_admin_cases (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  queue_id uuid NOT NULL UNIQUE REFERENCES public.delivery_queue(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','investigating','resolved')),
  note text NOT NULL DEFAULT '' CHECK (char_length(note) <= 600),
  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS nashra_admin_cases_updated_idx ON public.nashra_admin_cases(updated_at DESC);

CREATE TABLE IF NOT EXISTS public.nashra_admin_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  action text NOT NULL,
  target_id uuid,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS nashra_admin_audit_date_idx ON public.nashra_admin_audit(created_at DESC);

ALTER TABLE public.nashra_admin_cases ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.nashra_admin_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.nashra_admin_cases FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.nashra_admin_audit FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.nashra_admin_cases TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.nashra_admin_audit TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.nashra_admin_audit_id_seq TO service_role;
-- No RLS policies for authenticated: only the trusted server service_role may access.

CREATE OR REPLACE FUNCTION public.nashra_v34_save_case(
  p_queue_id uuid, p_status text, p_note text, p_actor uuid
)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_case_id uuid;
BEGIN
  IF auth.role() IS DISTINCT FROM 'service_role' THEN
    RAISE EXCEPTION 'NASHRA_ADMIN_ROLE_REQUIRED';
  END IF;
  IF p_status NOT IN ('open','investigating','resolved')
     OR char_length(btrim(coalesce(p_note,''))) NOT BETWEEN 8 AND 600 THEN
    RAISE EXCEPTION 'NASHRA_INVALID_CASE';
  END IF;
  -- No arbitrary queue IDs and no admin-side publishing/approval.
  IF NOT EXISTS (SELECT 1 FROM public.delivery_queue q WHERE q.id = p_queue_id
                 AND q.status IN ('blocked','needs_review','processing')) THEN
    RETURN NULL;
  END IF;
  INSERT INTO public.nashra_admin_cases (queue_id,status,note,updated_by)
  VALUES (p_queue_id,p_status,btrim(p_note),p_actor)
  ON CONFLICT (queue_id) DO UPDATE SET
    status=EXCLUDED.status, note=EXCLUDED.note, updated_by=EXCLUDED.updated_by, updated_at=now()
  RETURNING id INTO v_case_id;
  INSERT INTO public.nashra_admin_audit (actor_id,action,target_id,details)
  VALUES (p_actor, 'case.' || p_status, p_queue_id,
    jsonb_build_object('case_id',v_case_id,'note_length',char_length(btrim(p_note))));
  RETURN v_case_id;
END;
$$;
REVOKE ALL ON FUNCTION public.nashra_v34_save_case(uuid,text,text,uuid)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.nashra_v34_save_case(uuid,text,text,uuid) TO service_role;
